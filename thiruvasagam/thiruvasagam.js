const menu = document.getElementById("menu");
const select = document.getElementById("mobileMenu");
const frame = document.getElementById("readerFrame");

function label(item) {
  return item.number + "-" + item.title;
}

function openPage(item, updateHash = true) {
  frame.src = item.file;
  document.title = label(item) + " | திருவாசகம்";
  document.querySelectorAll("#menu a").forEach((link) => {
    const active = link.dataset.file === item.file;
    link.classList.toggle("active", active);
    if (active) link.setAttribute("aria-current", "page");
    else link.removeAttribute("aria-current");
  });
  select.value = item.file;
  if (updateHash) history.replaceState(null, "", "#" + item.number);
}

thiruvasagamItems.forEach((item) => {
  const link = document.createElement("a");
  link.href = item.file;
  link.dataset.file = item.file;
  link.textContent = label(item);
  link.addEventListener("click", (event) => {
    event.preventDefault();
    openPage(item);
  });
  menu.appendChild(link);

  const option = document.createElement("option");
  option.value = item.file;
  option.textContent = label(item);
  select.appendChild(option);
});

select.addEventListener("change", () => {
  const item = thiruvasagamItems.find((entry) => entry.file === select.value);
  if (item) openPage(item);
});

const requestedNumber = location.hash.slice(1).padStart(2, "0");
const initialItem =
  thiruvasagamItems.find((item) => item.number === requestedNumber) ||
  thiruvasagamItems[0];
openPage(initialItem, false);

